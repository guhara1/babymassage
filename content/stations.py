    title = f"{name} 출장마사지｜{region_kr} 역세권 안심 방문 안내 - {BRAND}"
    desc = (
        f"{name} 역세권 출장마사지·홈타이 방문 전 노선·생활권·이용 장소 확인 안내. "
        "건전한 방문 관리 서비스."
    )
    # desc 80자 이내 보정
    if len(desc) > 80:
        desc = f"{name} 역세권 출장마사지 방문 전 노선·생활권·이용 장소 확인 안내. 건전한 방문 관리 서비스."
