def _bc(gu_slug, dong_name):
    """수도권 > 인천 > 구 > 동 4단계 breadcrumb."""
    gu_name = _GU_NAME[gu_slug]
    return [
        ("수도권", "/"),
        ("인천", "/incheon/"),
        (gu_name, f"/incheon/{gu_slug}/"),
        (dong_name, ""),
    ]


def _dong_page(gu_slug, dong_slug, dong_name, overview, landmark_paras,
               move_paras, place_items, flow_paras, faq_items, related_pairs,
               desc):
    """동 페이지 공통 빌더. 각 인자는 동별 고유 문장을 받는다."""
    gu_name = _GU_NAME[gu_slug]

    sec_overview = section(f"{dong_name} 지역 개요 — {gu_name} 안에서의 위치", *overview)
    sec_landmark = section("대표 생활권·랜드마크", *landmark_paras)
    sec_move = section("가까운 역·이동 기준", *move_paras)
    sec_place = section(
        "이용 장소별 확인",
        "건물 유형에 따라 미리 확인해 두면 도착 후 대기 없이 방문이 이어집니다.",
        ul(place_items),
    )
    sec_flow = section(f"{dong_name} 방문 진행 흐름", *flow_paras)

    note = section(
        f"{dong_name} 예약·이용 시 참고 안내",
        f"{dong_name}에서 방문 일정을 잡으실 때는 예약 시점에 방문 가능한 시간대와 정확한 주소, "
        "건물 출입 방식을 함께 확인하시는 편이 좋습니다. 상담 단계에서 필요한 정보를 미리 정리해 "
        "두면 도착 전 연락을 드릴 때 위치를 빠르게 맞출 수 있어, 약속한 시간에 정확히 방문이 "
        f"진행됩니다. {dong_name}로 방문하는 모든 일정은 " + BRAND + "의 건전한 방문 관리 서비스 "
        "기준 안에서만 진행되며, 불법·선정적 요청에는 어떤 경우에도 응하지 않습니다.",
        "개인정보는 예약과 방문에 필요한 최소한의 범위에서만 확인하며, 일정 변경이 필요하실 때는 "
        "예약 변경 기준에 따라 조율해 드립니다. 처음 이용하시는 분이라면 예약 흐름과 확인 사항을 "
        "안내한 페이지를 함께 살펴보시면 도움이 됩니다. 궁금한 점은 편하신 시간에 전화 "
        + PHONE + " 로 문의해 주세요.",
    )

    sb = safe_booking_summary("인천")
    chk = checklist_section()
    related = related_section(related_pairs, h2="관련 구군·생활권 안내")
    faq = faq_section(faq_items)

    body = (
        sec_overview + sec_landmark + sec_move + sec_place + sec_flow
        + note + sb + chk + related + faq
    )

    return create_page(
        path=f"incheon/{gu_slug}/{dong_slug}/",
        title=f"{dong_name} 출장마사지｜{gu_name} 동별 안심 예약 방문 안내",
        desc=desc,
        h1=f"{dong_name} 출장마사지",
        breadcrumb=_bc(gu_slug, dong_name),
        body=body,
    )


