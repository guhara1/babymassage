def _dong_related_pairs(si_slug, dong_slug):
    city = CITY_INFO[si_slug]
    pairs = [(f"{city['name']} 출장마사지 안내", f"/gyeonggi/{si_slug}/")]
    siblings = [k for k in DONG_ORDER if k[0] == si_slug and k[1] != dong_slug]
    for s_si, s_dong in siblings:
        pairs.append((f"{DONG[(s_si, s_dong)]['name']} 출장마사지 안내",
                      f"/gyeonggi/{s_si}/{s_dong}/"))
    for life_name, life_slug in city["life"]:
        pairs.append((f"{life_name} 생활권 안내", f"/gyeonggi/life/{life_slug}/"))
    pairs.append(("오피스텔 이용 출장마사지 기준", "/use/officetel/"))
    pairs.append(("역세권 이용 안내", "/use/station-area/"))
    pairs.append(("외곽 지역 이용 안내", "/use/outer-area/"))
    pairs.append(("경기 출장마사지 홈", "/gyeonggi/"))
    pairs.append(("경기 지역 리포트", "/report/gyeonggi/"))
    return pairs


