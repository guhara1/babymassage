def _group_page(path, title, desc, h1, crumb_label, lead_paras, areas, use_note,
                inner_links, faqs, prep_paras):
    body = "".join([
        section("권역 개요", *lead_paras),
        section("포함 지역과 가까운 역", *areas),
        section("이용 장소별 확인 사항", *use_note),
        section(f"{crumb_label} 방문 준비와 동선 안내", *prep_paras),
        section(
            f"{crumb_label} 예약은 이렇게 진행됩니다",
            f"{crumb_label} 권역을 예약하실 때는 위에 정리한 포함 지역 가운데 어디에 해당하는지와 가까운 역, 이용 장소(자택·"
            "오피스텔·숙소)를 알려주시면 됩니다. 권역 안에서도 생활권과 건물 유형에 따라 출입 방식과 이동 동선이 달라, 정확한 "
            "주소와 건물명을 함께 말씀해 주시면 도착이 빨라집니다.",
            "예약 전에는 건물 출입 방식과 야간·주말 이용 가능 여부, 추가 이동비 발생 여부, 개인정보 처리 기준을 함께 확인하는 "
            f"것을 원칙으로 합니다. {BRAND}는 예약에 필요한 최소한의 정보만 받고, 모든 일정을 건전한 방문 관리 서비스 기준 안에서만 "
            "진행하며 불법·선정적 요청에는 응하지 않습니다.",
        ),
        safe_booking_summary("서울"),
        checklist_section(),
        related_section(inner_links, h2="이 권역의 생활권·자치구 안내"),
        faq_section(faqs),
        related_section([
            ("서울 홈으로", "/seoul/"),
            ("서울 지역 리포트", "/report/seoul/"),
            ("문의하기", "/contact/"),
        ]),
    ])
    PAGES.append(create_page(
        path=path, title=title, desc=desc, h1=h1,
        breadcrumb=[("수도권", "/"), ("서울", "/seoul/"), (crumb_label, "")],
        body=body,
    ))


