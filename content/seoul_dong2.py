# 각 행정동 데이터 구조:
#   gu_slug, gu_name      : 부모 자치구 슬러그/한글명 (seoul.py 와 일치)
#   dong_slug, dong_name  : 행정동 슬러그/한글명
#   overview              : [개요 문단들] — 소속 구·생활권 특성
#   landmarks             : [대표 생활권·랜드마크 li 문자열]
#   stations              : [가까운 지하철역 li 문자열]
#   place_kind            : "home" | "hotel" | "biz"  (이용 장소 강조)
#   tip                   : [방문 동선·확인 팁 문단들]
#   faqs                  : [(질문, 답변)] 2~3개
#   group_links           : [(라벨, /seoul/group/* 또는 /seoul/life/* 경로)] 실존하는 것만
#   sibling_links         : [(라벨, 같은 구 다른 동 경로)]


def _use_block(kind):
    if kind == "hotel":
        note = ("호텔·숙소를 이용하실 때는 객실 동·호수와 투숙 본인 확인, 프런트 통과 방식을 미리 점검하면 "
                "도착 후 동선이 매끄럽습니다. 자택·오피스텔을 이용하실 경우에는 건물명·호실과 공동현관 출입 "
                "방식을 함께 확인해 두시면 좋습니다.")
        pairs = [
            ("호텔·숙소 이용 기준", "/use/hotel/"),
            ("오피스텔 이용 기준", "/use/officetel/"),
            ("자택 이용 기준", "/use/home/"),
            ("야간 예약 안심 안내", "/use/night/"),
        ]
    elif kind == "biz":
        note = ("오피스·오피스텔을 이용하실 때는 빌딩 보안 통제와 방문자 등록, 엘리베이터 카드키, 야간 출입 절차를 "
                "미리 확인하면 로비 대기 시간을 줄일 수 있습니다. 숙소를 이용하실 경우에는 객실 호수와 프런트 "
                "확인 방식을 함께 점검해 두시면 좋습니다.")
        pairs = [
            ("업무지구 이용 기준", "/use/business-district/"),
            ("오피스텔 이용 기준", "/use/officetel/"),
            ("역세권 이용 기준", "/use/station-area/"),
            ("자택 이용 기준", "/use/home/"),
        ]
    else:  # home
        note = ("자택·오피스텔을 이용하실 때는 단지명·동·호수 또는 건물명·호실과 공동현관 출입 방식, 방문 차량 "
                "등록 절차를 미리 확인하면 도착이 빨라집니다. 숙소를 이용하실 경우에는 객실 정보와 프런트 통과 "
                "방식을 함께 확인해 두시면 좋습니다.")
        pairs = [
            ("자택 이용 기준", "/use/home/"),
            ("오피스텔 이용 기준", "/use/officetel/"),
            ("건물 출입 방식", "/safe-booking/building-access/"),
            ("역세권 이용 기준", "/use/station-area/"),
        ]
    return [note, links_ul(pairs)]


def _dong_page(gu_slug, gu_name, dong_slug, dong_name, overview, landmarks,
               stations, place_kind, tip, faqs, group_links, sibling_links):
    h1 = f"{dong_name} 출장마사지"
    path = f"seoul/{gu_slug}-gu/{dong_slug}/"

    related = list(sibling_links)
    related.append((f"{gu_name} 전체 안내", f"/seoul/{gu_slug}-gu/"))
    related.extend(group_links)
    related.append(("이용 장소별 안내", "/use/"))

    body = "".join([
        section("동 개요", *overview),
        section("대표 생활권·랜드마크", ul(landmarks)),
        section("가까운 지하철역", ul(stations)),
        section(f"{dong_name} 방문 동선과 확인 팁", *tip),
        section("이용 장소별 확인", *_use_block(place_kind)),
        section(
            f"{dong_name} 예약은 이렇게 진행됩니다",
            f"{dong_name} 방문을 예약하실 때는 방문 주소(단지명·동·호수 또는 건물명·호실)와 가까운 지하철역, "
            "이용 장소(자택·오피스텔·숙소)를 알려주시면 됩니다. 위에 정리한 대표 생활권과 가까운 역 안내를 참고해 "
            "어느 동선에 해당하는지 함께 말씀해 주시면 도착 시간을 더 정확히 잡을 수 있습니다.",
            "예약 전에는 건물 출입 방식과 야간·주말 이용 가능 여부, 추가 이동비 발생 여부, 개인정보 처리 기준을 "
            f"함께 확인하시는 것이 좋습니다. {BRAND}(전화 {PHONE})는 예약에 필요한 최소한의 정보만 받고, 모든 "
            "일정을 건전한 방문 관리 서비스 기준 안에서만 진행하며 불법·선정적 요청에는 어떤 경우에도 응하지 않습니다.",
        ),
        safe_booking_summary("서울"),
        checklist_section(),
        faq_section(faqs),
        related_section(related, h2=f"{dong_name} 관련 안내"),
        related_section([
            (f"{gu_name} 출장마사지 안내", f"/seoul/{gu_slug}-gu/"),
            ("서울 홈으로", "/seoul/"),
            ("서울 지역 리포트", "/report/seoul/"),
            ("문의하기", "/contact/"),
        ]),
    ])

    PAGES.append(create_page(
        path=path,
        title=f"{dong_name} 출장마사지｜{gu_name} 생활권·역세권 안심 예약",
        desc=f"{gu_name} {dong_name} 출장마사지 생활권·가까운 역·이용 장소 확인과 안심 예약 안내.",
        h1=h1,
        breadcrumb=[
            ("수도권", "/"),
            ("서울", "/seoul/"),
            (gu_name, f"/seoul/{gu_slug}-gu/"),
            (dong_name, ""),
        ],
        body=body,
    ))


