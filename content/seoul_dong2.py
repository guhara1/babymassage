# - URL 패턴: seoul/{gu}-gu/{dong-slug}/  (부모 구 경로는 seoul.py 와 정확히 일치)
# - breadcrumb 4단계: 수도권 > 서울 > {구} > {행정동}
# - 모든 페이지는 "건전한 방문 관리 서비스" 톤을 유지하며, 가격/요금 섹션을 두지 않고,
#   과장·선정·불법 암시를 하지 않는다. 각 동은 실제 지하철역·상권·랜드마크로 차별화한다.
# - 색인 본문(태그 제외) 2,000자 이상.

