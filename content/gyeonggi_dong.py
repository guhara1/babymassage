def _gu_related_pairs(si_slug, gu_slug):
    """상위 시 + 같은 시 다른 구 + 하위 동 일부 + 생활권 + 그룹/홈."""
    city = CITY_INFO[si_slug]
    g = GU[(si_slug, gu_slug)]
    group_path = city["group"]
    pairs = [(f"{city['name']} 출장마사지 안내", f"/gyeonggi/{si_slug}/")]

    # 같은 시 다른 구
    for s_si, s_gu in GU_ORDER:
        if s_si == si_slug and s_gu != gu_slug:
            pairs.append((f"{GU[(s_si, s_gu)]['name']} 출장마사지 안내",
                          f"/gyeonggi/{s_si}/{s_gu}/"))

    # 하위 동 일부 (최대 3개)
    child_dongs = [k for k in DONG_GU_ORDER if k[0] == si_slug and k[1] == gu_slug][:3]
    for _, _, d_slug in child_dongs:
        d = DONG_GU[(si_slug, gu_slug, d_slug)]
        pairs.append((f"{g['name']} {d['name']} 방문 안내",
                      f"/gyeonggi/{si_slug}/{gu_slug}/{d_slug}/"))

    # 생활권
    for life_name, life_slug in city["life"]:
        pairs.append((f"{life_name} 생활권 안내", f"/gyeonggi/life/{life_slug}/"))

    pairs.append(("오피스텔 이용 출장마사지 기준", "/use/officetel/"))
    pairs.append(("경기 출장마사지 홈", "/gyeonggi/"))
    pairs.append(("경기 지역 리포트", "/report/gyeonggi/"))
    return pairs


