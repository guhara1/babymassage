# 관련 링크 (부모 시 + 같은 시 다른 동 + 가까운 생활권 + 이용 장소)
# ──────────────────────────────────────────

def _related_pairs(si_slug, dong_slug):
    city_name = CITY_INFO[si_slug]["name"]
    pairs = [(f"{city_name} 출장마사지 안내", f"/gyeonggi/{si_slug}/")]

    # 같은 시 다른 동 (최대 4개)
    siblings = [k for k in DONG_ORDER if k[0] == si_slug and k[1] != dong_slug][:4]
    for s_si, s_dong in siblings:
        pairs.append((f"{DONG[(s_si, s_dong)]['name']} 출장마사지 안내",
                      f"/gyeonggi/{s_si}/{s_dong}/"))

    # 가까운 생활권 (이 동의 nearby + 시 단위 생활권)
    seen = set()
    d = DONG[(si_slug, dong_slug)]
    if "nearby" in d:
        pairs.append(d["nearby"])
        seen.add(d["nearby"][1])
    for life_name, life_slug in CITY_INFO[si_slug]["life"]:
        href = f"/gyeonggi/life/{life_slug}/"
        if href not in seen:
            pairs.append((f"{life_name} 생활권 안내", href))
            seen.add(href)

    # 이용 장소 + 경기 홈/리포트
    pairs.append(("오피스텔 이용 출장마사지 기준", "/use/officetel/"))
    pairs.append(("역세권 이용 안내", "/use/station-area/"))
    pairs.append(("경기 출장마사지 홈", "/gyeonggi/"))
    pairs.append(("경기 지역 리포트", "/report/gyeonggi/"))
    return pairs


