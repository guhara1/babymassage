def _related_pairs_for_city(slug):
    """같은 그룹의 다른 시군 + 관련 생활권 + 그룹/홈 링크."""
    c = CITY[slug]
    group_path = c["group_path"]
    siblings = [s for s in GROUP_CITIES.get(group_path, []) if s in CITY and s != slug][:5]
    pairs = []
    for s in siblings:
        pairs.append((f"{CITY[s]['name']} 출장마사지 안내", f"/gyeonggi/{s}/"))
    # 관련 생활권 매핑
    life_map = {
        "suwon": ["suwon-station-ingye", "gwanggyo-yeongtong"],
        "seongnam": ["bundang-pangyo"],
        "yongin": ["jukjeon-suji"],
        "hwaseong": ["dongtan-newtown"],
        "bucheon": ["bucheon-station-sangdong"],
        "anyang": ["anyang-beomgye-pyeongchon"],
        "goyang": ["ilsan-kintex"],
        "uijeongbu": ["uijeongbu-station-minrak"],
        "hanam": ["hanam-misa"],
    }
    for life in life_map.get(slug, []):
        pairs.append((f"{LIFE[life]['name']} 생활권 안내", f"/gyeonggi/life/{life}/"))
    pairs.append((f"{c['group']} 묶음 안내", f"/gyeonggi/group/{group_path}/"))
    pairs.append(("경기 출장마사지 홈", "/gyeonggi/"))
    pairs.append(("경기 지역 리포트", "/report/gyeonggi/"))
    return pairs


