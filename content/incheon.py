def _gu_page(slug, name, intro_paras, life_items, stations, place_items,
             related_pairs, faq_items, region_label, flow_paras, tip_paras):
    intro = section(f"{name} 지역 개요", *intro_paras)
    life = section("대표 생활권", ul(life_items))
